/**
 * Turns the ledger into the text of `APPLICATIONS.md`.
 *
 * Why it exists: a plain file the user can open, search, print or keep in git, that always matches
 * the database. It is generated; edits belong in `scout applications` or the Applications page.
 *
 * Example: the text starts with `# Applications`, then "Needs attention", the open applications
 * table, the closed ones, and one section per application with its recruiter and history.
 */
import type { LedgerDetail } from "./types.js";
import { FINISHED_STATUSES } from "./types.js";

/** The file name written in the data folder. */
export const LEDGER_FILE_NAME = "APPLICATIONS.md";

/** A table cell: pipes and line breaks would break the table, so they are replaced. */
function cell(value: string | undefined): string {
  const text = (value ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\s*\r?\n\s*/g, " ")
    .trim();
  return text === "" ? "-" : text;
}

/** The date part of an ISO time, or `-` when empty. */
function day(iso: string): string {
  return iso === "" ? "-" : iso.slice(0, 10);
}

/** Recruiter name with firm, for one table cell. */
function recruiterCell(entry: LedgerDetail): string {
  const { recruiterName, recruiterFirm } = entry.details;
  if (recruiterName === undefined && recruiterFirm === undefined) return "-";
  return [recruiterName, recruiterFirm === undefined ? undefined : `(${recruiterFirm})`]
    .filter((part) => part !== undefined)
    .join(" ");
}

/** Phone and email in one cell, so the user can find who called. */
function contactCell(entry: LedgerDetail): string {
  const parts = [entry.details.recruiterPhone, entry.details.recruiterEmail].filter(
    (part): part is string => part !== undefined,
  );
  return parts.length === 0 ? "-" : parts.join(", ");
}

/** The header and rows of a table of applications. */
function table(entries: LedgerDetail[]): string[] {
  const lines = [
    "| Applied | Company | Role | Job ID | Status | Recruiter | Contact | Next step | Link |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const entry of entries) {
    const next = [entry.details.nextStepDate, entry.details.nextStep]
      .filter((part) => part !== undefined && part !== "")
      .join(" ");
    lines.push(
      `| ${[
        day(entry.appliedAt),
        cell(entry.company),
        cell(entry.title),
        cell(entry.jobNumber),
        cell(entry.status),
        cell(recruiterCell(entry)),
        cell(contactCell(entry)),
        cell(next),
        entry.link === "" ? "-" : `<${entry.link.replace(/[<>\s]/g, "")}>`,
      ].join(" | ")} |`,
    );
  }
  return lines;
}

/** One application's section: facts, then its history. */
function section(entry: LedgerDetail): string[] {
  const lines = [`### ${entry.company}: ${entry.title}`, ""];
  const facts: [string, string | undefined][] = [
    ["Scout id", entry.id],
    ["Job ID", entry.jobNumber],
    ["Status", entry.status],
    ["Applied", entry.appliedAt === "" ? undefined : day(entry.appliedAt)],
    ["Applied via", entry.details.appliedVia],
    ["Link", entry.link === "" ? undefined : entry.link],
    ["Location", entry.location],
    ["Recruiter", entry.details.recruiterName],
    ["Recruiter firm", entry.details.recruiterFirm],
    ["Recruiter email", entry.details.recruiterEmail],
    ["Recruiter phone", entry.details.recruiterPhone],
    ["Recruiter LinkedIn", entry.details.recruiterLinkedin],
    ["Next step", entry.details.nextStep],
    ["Next step date", entry.details.nextStepDate],
  ];
  for (const [label, value] of facts) {
    if (value !== undefined && value !== "")
      lines.push(`- ${label}: ${value.replace(/\s*\r?\n\s*/g, " ")}`);
  }
  lines.push("", "History:", "");
  if (entry.events.length === 0) lines.push("- Nothing recorded yet.");
  for (const event of entry.events) {
    const who = event.contact === undefined ? "" : ` (${event.contact})`;
    const more =
      event.detail === undefined || event.detail === ""
        ? ""
        : ` - ${event.detail.replace(/\s*\r?\n\s*/g, " ")}`;
    lines.push(
      `- ${event.at.slice(0, 16).replace("T", " ")} [${event.kind}]${who} ${event.summary.replace(/\s*\r?\n\s*/g, " ")}${more}`,
    );
  }
  lines.push("");
  return lines;
}

/**
 * Builds the whole file text from the ledger entries (newest activity first).
 * Example: with no entries it still returns a valid file that says nothing is recorded.
 */
export function renderLedgerMarkdown(entries: LedgerDetail[], generatedAt: Date): string {
  const open = entries.filter((entry) => !FINISHED_STATUSES.includes(entry.status));
  const finished = entries.filter((entry) => FINISHED_STATUSES.includes(entry.status));
  const due = entries.filter((entry) => entry.followUpDue);
  const lines = [
    "# Applications",
    "",
    `Generated by Scout on ${generatedAt.toISOString().slice(0, 16).replace("T", " ")} UTC. Do not edit this file: it is rewritten after every change. Update an application with \`scout applications\` or on the Applications page.`,
    "",
    `${entries.length} application${entries.length === 1 ? "" : "s"}: ${open.length} open, ${finished.length} finished.`,
    "",
  ];
  if (due.length > 0) {
    lines.push("## Needs attention", "");
    for (const entry of due) {
      lines.push(
        `- ${entry.company}, ${entry.title} (${entry.id}): ${entry.details.nextStep ?? "follow up"} (due ${entry.details.nextStepDate ?? ""})`,
      );
    }
    lines.push("");
  }
  lines.push("## Open", "");
  lines.push(...(open.length === 0 ? ["Nothing open."] : table(open)), "");
  lines.push("## Finished", "");
  lines.push(...(finished.length === 0 ? ["Nothing finished."] : table(finished)), "");
  lines.push("## Details", "");
  if (entries.length === 0) lines.push("Nothing is recorded yet.", "");
  for (const entry of [...open, ...finished]) lines.push(...section(entry));
  return `${lines.join("\n").trimEnd()}\n`;
}
